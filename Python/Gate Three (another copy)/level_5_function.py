def new_number():
    numbers = [10,11,12]
    new_list = [-1]*2
    numbers.extend(new_list)
    return numbers
result = new_number()
print (result)

def two_number():
    numbers = [10,11,12,13,14]
    numbers.pop(4)
    numbers.pop(3)
    numbers.pop(2)
    return numbers
result = two_number()
print (result)

